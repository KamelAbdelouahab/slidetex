#!/usr/bin/env node
/*
 * Builds the IE11 bundle used by PowerPoint 2016 / 2019 perpetual on Windows (their add-in
 * webview is Internet Explorer 11). Modern webviews (Microsoft 365, 2021+, Mac, Web) ignore it.
 *   public/legacy/polyfills.js  : core-js + fetch + AbortController + TextEncoder + DOM bits
 *   public/legacy/app.js        : snippets + svgtools + taskpane transpiled to ES5
 *   public/legacy/taskpane.css  : CSS with custom properties resolved (light theme)
 */
"use strict";
const fs = require("fs");
const path = require("path");
const babel = require("@babel/core");

const root = path.join(__dirname, "..");
const pub = path.join(root, "public");
const out = path.join(pub, "legacy");
fs.mkdirSync(out, { recursive: true });
const nm = (p) => fs.readFileSync(path.join(root, "node_modules", p), "utf8");

const domPolyfills = `
(function () {
  [Element.prototype, CharacterData.prototype, DocumentType.prototype].forEach(function (p) {
    if (!p.remove) p.remove = function () { if (this.parentNode) this.parentNode.removeChild(this); };
  });
  if (!Element.prototype.matches) Element.prototype.matches = Element.prototype.msMatchesSelector;
  if (!Element.prototype.closest) Element.prototype.closest = function (s) {
    var el = this; while (el && el.nodeType === 1) { if (el.matches(s)) return el; el = el.parentNode; } return null;
  };
  if (window.performance && !performance.now) performance.now = function () { return Date.now(); };
  // HTML5 "hidden" attribute is not styled in IE10-
  var st = document.createElement("style"); st.textContent = "[hidden]{display:none!important}"; document.head.appendChild(st);
  // Light theme stylesheet with resolved CSS variables.
  var l = document.createElement("link"); l.rel = "stylesheet"; l.href = "legacy/taskpane.css"; document.head.appendChild(l);
})();
`;

const polyfills = [
  "/* SlideTeX legacy polyfills (IE11) */",
  nm("core-js-bundle/minified.js"),
  nm("regenerator-runtime/runtime.js"),
  nm("whatwg-fetch/dist/fetch.umd.js"),
  nm("abortcontroller-polyfill/dist/umd-polyfill.js"),
  nm("fast-text-encoding/text.min.js"),
  domPolyfills,
].join("\n;\n");
fs.writeFileSync(path.join(out, "polyfills.js"), polyfills);

const parts = ["snippets.js", "svgtools.js", "taskpane.js"].map((f) => {
  const src = fs.readFileSync(path.join(pub, f), "utf8");
  return babel.transformSync(src, {
    filename: f,
    babelrc: false,
    configFile: false,
    sourceType: "script",
    presets: [["@babel/preset-env", { targets: { ie: "11" }, modules: false, useBuiltIns: false }]],
  }).code;
});
fs.writeFileSync(path.join(out, "app.js"), "/* SlideTeX (ES5 build — generated by scripts/build-legacy.js, do not edit) */\n" + parts.join("\n;\n"));

// Resolve CSS custom properties with their light-theme values.
let css = fs.readFileSync(path.join(pub, "taskpane.css"), "utf8");
const vars = {};
const rootBlock = css.match(/:root\s*{([^}]*)}/)[1];
rootBlock.replace(/--([\w-]+)\s*:\s*([^;]+);/g, (_, k, v) => (vars[k] = v.trim()));
css = css
  .replace(/@media \(prefers-color-scheme: dark\)\s*{[\s\S]*?\n}\n/, "")
  .replace(/:root\[data-theme="dark"\]\s*{[^}]*}/, "")
  .replace(/var\(--([\w-]+)\)/g, (_, k) => vars[k] || "inherit");
fs.writeFileSync(path.join(out, "taskpane.css"), "/* generated by scripts/build-legacy.js */\n" + css);

console.log("Legacy (IE11) bundle written to public/legacy/");
