#!/usr/bin/env node
/*
 * Builds dist-exe/SlideTeX.exe : a single self-contained Windows executable (Bun runtime +
 * server + task pane + MathJax + resvg-wasm). Users need neither Node.js nor npm.
 *
 *   node scripts/build-exe.js            -> Windows x64 exe
 *   node scripts/build-exe.js --linux    -> Linux binary as well (for testing)
 * Requires `bun` on PATH (npm i -g bun).
 */
"use strict";
const fs = require("fs");
const path = require("path");
const { execFileSync } = require("child_process");

const root = path.join(__dirname, "..");
const build = path.join(root, "build");
const outDir = path.join(root, "dist-exe");
fs.mkdirSync(build, { recursive: true });
fs.mkdirSync(outDir, { recursive: true });

const MIME = {
  ".html": "text/html; charset=utf-8",
  ".js": "application/javascript; charset=utf-8",
  ".css": "text/css; charset=utf-8",
  ".png": "image/png",
  ".svg": "image/svg+xml",
  ".json": "application/json",
  ".woff": "font/woff",
  ".wasm": "application/wasm",
  ".xml": "application/xml",
};

const files = {};
function addDir(dir, prefix, skip) {
  for (const name of fs.readdirSync(dir)) {
    const full = path.join(dir, name);
    const rel = prefix + "/" + name;
    if (skip && skip(rel)) continue;
    if (fs.statSync(full).isDirectory()) addDir(full, rel, skip);
    else files[rel] = [MIME[path.extname(name)] || "application/octet-stream", fs.readFileSync(full).toString("base64")];
  }
}

// Make sure the IE11 bundle matches the current sources.
execFileSync(process.execPath, [path.join(__dirname, "build-legacy.js")], { stdio: "inherit" });

addDir(path.join(root, "public"), "");
// MathJax: the full TeX+SVG component and what it may lazy-load (no speech engine, no CHTML output).
addDir(path.join(root, "node_modules", "mathjax", "es5"), "/vendor/mathjax", (rel) =>
  /\/(sre|output\/chtml)(\/|$)|chtml|mml-svg\.js$|\.map$/.test(rel)
);
files["/__resvg.wasm"] = ["application/wasm", fs.readFileSync(path.join(root, "node_modules", "@resvg", "resvg-wasm", "index_bg.wasm")).toString("base64")];

const manifestTemplate = fs.readFileSync(path.join(root, "templates", "manifest.template.xml"), "utf8");
fs.writeFileSync(
  path.join(build, "assets.generated.js"),
  "/* generated by scripts/build-exe.js */\nmodule.exports = " + JSON.stringify({ manifestTemplate, files }) + ";\n"
);
const total = Object.values(files).reduce((n, f) => n + f[1].length * 0.75, 0);
console.log(`Embedded ${Object.keys(files).length} files (${(total / 1048576).toFixed(1)} MB)`);

const entry = path.join(root, "exe", "main.js");
const targets = [["bun-windows-x64", path.join(outDir, "SlideTeX.exe")]];
if (process.argv.includes("--linux")) targets.push(["bun-linux-x64", path.join(outDir, "slidetex-linux")]);
for (const [target, out] of targets) {
  const extra = target.includes("windows") && fs.existsSync(path.join(build, "icon.ico")) ? ["--windows-icon=" + path.join(build, "icon.ico")] : [];
  const argv = ["build", "--compile", "--minify", `--target=${target}`, entry, "--outfile", out, ...extra];
  try {
    execFileSync("bun", argv, { stdio: "inherit", cwd: root });
  } catch (e) {
    if (!extra.length) throw e;
    console.warn("Icon embedding failed when cross-compiling; building without icon.");
    execFileSync("bun", argv.filter((a) => !a.startsWith("--windows-icon")), { stdio: "inherit", cwd: root });
  }
  console.log(`→ ${path.relative(root, out)} (${(fs.statSync(out).size / 1048576).toFixed(0)} MB)`);
}
